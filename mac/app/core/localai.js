/* ---------- 知识库检索兜底（二元组匹配，零依赖） ---------- */
function searchKnowledge(question, knowledge) {
  const clean = String(question).replace(/[，。？！、,.?!：:"'()（）\s]/g, "");
  if (clean.length < 2) return null;
  const grams = [];
  for (let i = 0; i < clean.length - 1; i++) grams.push(clean.slice(i, i + 2));
  let best = null, bestScore = 0;
  for (const para of String(knowledge).split("\n\n")) {
    if (para.length < 40) continue;
    let score = 0;
    for (const g of grams) if (para.includes(g)) score++;
    if (score > bestScore) { bestScore = score; best = para; }
  }
  const need = clean.length <= 4 ? 2 : Math.max(2, Math.ceil(grams.length * 0.3));
  if (best && bestScore >= need) {
    const cut = best.length > 700 ? best.slice(0, 700) + "……" : best;
    return "根据中文程开发文档，相关内容如下（可直接照着写）：\n\n" + cut + "\n\n需要更具体的完整示例的话，告诉我你想做什么。";
  }
  return null;
}

/* ---------- 算术：本地大模型不可用时的兜底，算个数不能哑火 ---------- */
function tryArithmetic(raw) {
  let s = String(raw || "")
    .replace(/\s+/g, "")
    .replace(/乘以|乘上|×|x(?=\d)/g, "*").replace(/除以|÷|\/\//g, "/")
    .replace(/加|加上|\+/g, "+").replace(/减去|减|\-/g, "-");
  /* 只保留数字、运算符、括号、小数点，其余一律拒绝（安全求值） */
  const expr = s.match(/[\d+\-*/.()%]+/);
  if (!expr) return null;
  const e = expr[0];
  if (!/\d/.test(e) || !/[+\-*/%]/.test(e)) return null;
  if (!/^[\d+\-*/.()%\s]+$/.test(e)) return null;
  /* 必须在原句里占主体，避免误判聊天里夹带的数字 */
  const rest = String(raw).replace(/[\d+\-*/.()%\s+加减乘乘以除以×÷]+/g, "");
  if (/[，。！？吗呢吧啊呀]/.test(rest) && rest.replace(/[，。！？吗呢吧啊呀多少等于几算下一下?？]/g, "").length > 6) return null;
  try {
    const v = Function('"use strict"; return (' + e + ")")();
    if (typeof v !== "number" || !isFinite(v)) return null;
    const shown = Number.isInteger(v) ? String(v) : String(Math.round(v * 1e6) / 1e6);
    return "答案是：" + shown + "。\n\n（算式由内置计算引擎直接算出，保证准确）";
  } catch (e2) { return null; }
}

