/* ---------- 用户文件存取 ---------- */
function 读用户文件表() {
  try { return JSON.parse(localStorage.getItem(用户文件键)) || {}; }
  catch (e) { return {}; }
}

function 存用户文件表(表) {
  localStorage.setItem(用户文件键, JSON.stringify(表));
}

function 读用户文件(名) {
  const 表 = 读用户文件表();
  return 表[名] !== undefined ? 表[名] : null;
}

function 写用户文件(名, 内容) {
  const 表 = 读用户文件表();
  表[名] = 内容;
  存用户文件表(表);
}

function 删用户文件(名) {
  const 表 = 读用户文件表();
  delete 表[名];
  存用户文件表(表);
}

/* ---------- 导出 / 导入 ---------- */
function 导出文件(名, 内容) {
  const 块 = new Blob(["\ufeff" + 内容], { type: "text/plain;charset=utf-8" });
  const 链接 = document.createElement("a");
  链接.href = URL.createObjectURL(块);
  链接.download = /\.\w{2,4}$/.test(名) ? 名 : 名 + ".zy";
  链接.click();
  setTimeout(() => URL.revokeObjectURL(链接.href), 3000);
}

function 导入文件(file, 回调) {
  const 读者 = new FileReader();
  读者.onload = () => 回调(file.name.replace(/\.zy$/i, ""), 读者.result.replace(/^\ufeff/, ""));
  读者.readAsText(file, "utf-8");
}
